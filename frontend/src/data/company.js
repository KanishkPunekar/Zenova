/** Full viewform URL, optionally pre-filled with a product name. */
export function googleFormUrl({ embedded = false, product = "" } = {}) {
  if (!googleForm.formId) return null;

  const url = new URL(
    `https://docs.google.com/forms/d/e/${googleForm.formId}/viewform`,
  );
  if (embedded) url.searchParams.set("embedded", "true");
  if (product && googleForm.productEntryId) {
    url.searchParams.set("usp", "pp_url");
    url.searchParams.set(googleForm.productEntryId, product);
  }
  return url.toString();
}

